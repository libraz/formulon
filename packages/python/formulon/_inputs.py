"""Input normalisation shared by the facade: colours, A1 text in records and dates.

Every helper here turns one accepted input form into the shape the packers
write, so an entry point that takes a ``ColorInput``, an A1 string inside a
record or a ``datetime`` behaves the same whichever method it belongs to.
"""

from __future__ import annotations

import dataclasses
import datetime
import math
import numbers
import re
from typing import Any, Dict, Optional, Tuple

from ._c import FormulonError
from ._status import StatusCode
from .workbook import CellAddress, CellRect, Color, ColorKind, SheetRect, Workbook

__all__ = [
    "RECORD_RANGE_FIELDS",
    "color_input",
    "date_serial",
    "normalize_record_ranges",
    "optional_color_input",
    "serial_datetime",
    "sheet_rect",
]

# <record-range-fields> generated by tools/codegen/gen_facade_tables.py; do not edit
RECORD_RANGE_FIELDS = {
    "AutoFilterSortCondition": {"ref": "CellRect"},
    "AutoFilterSortState": {"ref": "CellRect", "conditions": "AutoFilterSortCondition[]"},
    "ConditionalFormatInput": {"ranges": "CellRect[]"},
    "DataValidationInput": {"ranges": "CellRect[]"},
    "PivotInput": {"anchor": "CellAddress"},
}
# </record-range-fields>

_COLOR_TEXT = re.compile(r"#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{8})")


def _invalid(message: str) -> FormulonError:
    return FormulonError(StatusCode.INVALID_ARGUMENT, _diagnostic_override=(message, ""))


# ---------------------------------------------------------------------------
# Colours
# ---------------------------------------------------------------------------


def color_input(value: Any, label: str) -> Color:
    """A ``ColorInput`` as a :class:`Color`: ``"#RRGGBB"`` (opaque), ``"#AARRGGBB"`` or a :class:`Color`."""
    if isinstance(value, str):
        if not _COLOR_TEXT.fullmatch(value):
            raise TypeError(f'formulon: {label} must be "#RRGGBB" or "#AARRGGBB", got {value!r}')
        digits = value[1:] if len(value) == 9 else "FF" + value[1:]
        return Color(kind=ColorKind.RGB, rgb=int(digits, 16))
    if not isinstance(value, Color):
        raise TypeError(f"formulon: {label} must be a colour string or a Color, got {type(value).__name__}")
    return value


def optional_color_input(value: Any, label: str) -> Color:
    """:func:`color_input`, with ``None`` read as the absent colour (``ColorKind.NONE``)."""
    return Color() if value is None else color_input(value, label)


# ---------------------------------------------------------------------------
# A1 text in records
# ---------------------------------------------------------------------------


def _parse(workbook: Workbook, text: str) -> Tuple[Optional[str], CellRect]:
    """``(sheet qualifier, rectangle)`` of one A1 reference; anything else is a ``FormulaSyntaxError``."""
    ref = workbook.parse_reference(text)
    return ref.sheet_name, ref.rect


def _cell_rect(workbook: Workbook, value: Any, label: str) -> CellRect:
    if isinstance(value, CellRect):
        return value
    if not isinstance(value, str):
        raise TypeError(f"formulon: {label} must be a CellRect or an A1 string, got {type(value).__name__}")
    qualifier, rect = _parse(workbook, value)
    if qualifier is not None:
        raise _invalid(f"{label}: {value!r} names a sheet; the record's sheet is implied")
    return rect


def sheet_rect(workbook: Workbook, value: Any, sheet: Optional[int], label: str) -> SheetRect:
    """A ``SheetRect`` or its A1 text; an unqualified range resolves on ``sheet``, an error without one."""
    if isinstance(value, SheetRect):
        return value
    if not isinstance(value, str):
        raise TypeError(f"formulon: {label} must be a SheetRect or an A1 string, got {type(value).__name__}")
    qualifier, rect = _parse(workbook, value)
    if qualifier is not None:
        return SheetRect(sheet=workbook.sheet(qualifier).index, rect=rect)
    if sheet is None:
        raise _invalid(f"{label}: {value!r} has no sheet name and the record has no sheet")
    return SheetRect(sheet=sheet, rect=rect)


def _cell_address(workbook: Workbook, value: Any, label: str) -> CellAddress:
    if isinstance(value, CellAddress):
        return value
    if not isinstance(value, str):
        raise TypeError(f"formulon: {label} must be a CellAddress or an A1 string, got {type(value).__name__}")
    rect = _cell_rect(workbook, value, label)
    if rect.first_row != rect.last_row or rect.first_col != rect.last_col:
        raise _invalid(f"{label}: {value!r} is not a single cell")
    return CellAddress(row=rect.first_row, col=rect.first_col)


def _normalize_field(workbook: Workbook, kind: str, value: Any, sheet: Optional[int], label: str) -> Any:
    if value is None:
        return None
    if kind.endswith("[]"):
        element = kind[:-2]
        items = [value] if isinstance(value, str) else value
        if isinstance(items, (bytes, dict)) or not hasattr(items, "__iter__"):
            raise TypeError(f"formulon: {label} must be a list or one A1 string, got {type(value).__name__}")
        return [_normalize_field(workbook, element, item, sheet, f"{label}[{i}]") for i, item in enumerate(items)]
    if kind == "CellRect":
        return _cell_rect(workbook, value, label)
    if kind == "SheetRect":
        return sheet_rect(workbook, value, sheet, label)
    if kind == "CellAddress":
        return _cell_address(workbook, value, label)
    return normalize_record_ranges(value, workbook, sheet=sheet, label=label)


def normalize_record_ranges(record: Any, workbook: Workbook, *, sheet: Optional[int] = None, label: str = "") -> Any:
    """``record`` with every A1 string in its address fields resolved, by :data:`RECORD_RANGE_FIELDS`.

    A ``CellRect`` field takes an unqualified A1 range, a ``CellRect[]`` field a
    list of them or one string, a ``SheetRect`` field a qualified range (an
    unqualified one resolves on ``sheet``) and a ``CellAddress`` field one
    cell. A record type the table does not list is returned as it is.

    Raises:
      TypeError: when a field holds neither its record type nor a string.
      FormulaSyntaxError: for a string that is not one A1 range (blank, multi-area, past the grid).
      InvalidArgumentError: for a sheet-qualified ``CellRect`` string, or an
        unqualified ``SheetRect`` string without ``sheet``.
    """
    schema: Dict[str, str] = RECORD_RANGE_FIELDS.get(type(record).__name__, {})
    if not schema:
        return record
    prefix = label or type(record).__name__
    changes = {
        name: _normalize_field(workbook, kind, getattr(record, name), sheet, f"{prefix}.{name}")
        for name, kind in schema.items()
    }
    return dataclasses.replace(record, **changes)


