# The en-US format code a General cell takes for each written date kind.
_DATE_FORMAT = "m/d/yyyy"
_DATETIME_FORMAT = "m/d/yyyy h:mm"
_TIME_FORMAT = "h:mm:ss"


def _day_fraction(t: datetime.time) -> float:
    return (t.hour * 3600 + t.minute * 60 + t.second) / 86400 + t.microsecond / 86400000000


def date_serial(value: Any, *, date1904: bool) -> Tuple[float, str]:
    """``(serial, en-US format code)`` of a ``date``, naive ``datetime`` or naive ``time``.

    A ``time`` is the fraction of a day in ``[0, 1)``.

    Raises:
      TypeError: for a ``timedelta`` or any other type.
      ValueError: for a ``datetime`` or ``time`` that carries a time zone.
      InvalidArgumentError: when the date lies outside the date system.
    """
    from .metadata import convert_civil_to_serial

    if isinstance(value, datetime.datetime):
        if value.tzinfo is not None:
            raise ValueError("formulon: a datetime written to a cell must be naive; it is a wall-clock reading")
        day = convert_civil_to_serial(value.date(), date1904=date1904)
        return day + _day_fraction(value.time()), _DATETIME_FORMAT
    if isinstance(value, datetime.date):
        return convert_civil_to_serial(value, date1904=date1904), _DATE_FORMAT
    if isinstance(value, datetime.time):
        if value.tzinfo is not None:
            raise ValueError("formulon: a time written to a cell must be naive; it is a wall-clock reading")
        return _day_fraction(value), _TIME_FORMAT
    raise TypeError(f"formulon: expected a date, datetime or time, got {type(value).__name__}")


def serial_datetime(serial: Any, *, date1904: bool) -> datetime.datetime:
    """The naive ``datetime`` a serial names, its fraction rounded to the microsecond.

    Raises:
      TypeError: when ``serial`` is not a number.
      InvalidArgumentError: for a non-finite serial, or one outside the date
        system (before day 1 of the 1900 system or day 0 of the 1904 one, or
        past 9999-12-31).
    """
    from .metadata import convert_serial_to_civil

    if isinstance(serial, bool) or not isinstance(serial, numbers.Real):
        raise TypeError(f"formulon: a serial must be a number, got {type(serial).__name__}")
    x = float(serial)
    if not math.isfinite(x):
        raise _invalid(f"{x!r} is not a date serial")
    whole = math.floor(x)
    day = convert_serial_to_civil(whole, date1904=date1904)
    try:
        return day + datetime.timedelta(microseconds=round((x - whole) * 86400000000))
    except OverflowError:
        raise _invalid(f"{x!r} rounds past 9999-12-31") from None
