#!/usr/bin/env python3
"""Generates the per-code-point byte widths behind LENB and the other byte-counting text functions.

Input:   tools/dbcs/lenb_widths.json, one entry per code page: [first, last, width]
         runs over the BMP (surrogates excluded) from Mac Excel's LENB of each
         code point. Width is 1 or 2; -1 marks a code point Excel cannot
         produce (noncharacters), which takes the width of its neighbours.
Output:  src/eval/dbcs_lenb_table.cpp

The width of a code point is neither the code page nor East Asian Width, so
it is stored as the sorted code points where the width toggles, starting at
width 1 from U+0000. A code page absent from the input keeps the engine's
default width (2 for every non-ASCII character).

Usage:
    python3 tools/dbcs/generate_lenb_tables.py          # rewrite the output
    python3 tools/dbcs/generate_lenb_tables.py --check  # exit 1 on drift
    python3 tools/dbcs/generate_lenb_tables.py --verify-probe DIR
        # DIR holds lenb_<locale>.json sweeps ({"cps": [...], "lenb": [...]});
        # compares every measured code point with the generated toggles
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RUNS_PATH = REPO_ROOT / "tools" / "dbcs" / "lenb_widths.json"
OUTPUT_PATH = REPO_ROOT / "src" / "eval" / "dbcs_lenb_table.cpp"
REGENERATION_GUIDANCE = "Regenerate with: python3 tools/dbcs/generate_lenb_tables.py"

# Input key -> DbcsCodepage enumerator, in lookup order.
CODEPAGES = {
    "jis0208": "kJis0208",
    "gb2312": "kGb2312",
    "ksx1001": "kKsX1001",
    "big5": "kBig5",
}
PROBE_LOCALES = {"jis0208": "ja_JP", "ksx1001": "ko_KR", "big5": "zh_TW"}


def toggles(runs: list[list[int]]) -> list[int]:
    """Code points where the width flips between 1 and 2."""
    out: list[int] = []
    current = 1
    for first, _last, width in runs:
        if width != -1 and width != current:
            out.append(first)
            current = width
    return out


def width_at(points: list[int], cp: int) -> int:
    return 1 + sum(1 for p in points if p <= cp) % 2


def render(table: dict[str, list[int]]) -> str:
    lines = [
        "// GENERATED by tools/dbcs/generate_lenb_tables.py from tools/dbcs/lenb_widths.json; do not edit.",
        "// Code points where the LENB width of a BMP character flips between 1 and 2, per code page.",
        f"// @size-budget: {max(1, (sum(len(v) for v in table.values()) * 2 + 1023) // 1024)} KB",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        '#include "eval/dbcs_table.h"',
        "",
        "namespace formulon {",
        "namespace eval {",
        "namespace {",
        "",
    ]
    for key, points in table.items():
        # Fixed-width items, 14 per line: the layout clang-format keeps for a 120-column file.
        rows = [points[i : i + 14] for i in range(0, len(points), 14)]
        body = "\n".join("    " + ", ".join(f"0x{p:04X}" for p in row) + "," for row in rows)
        lines += [f"constexpr std::uint16_t k{key.capitalize()}Toggles[] = {{", body, "};", ""]
    lines += [
        "}  // namespace",
        "",
        "DbcsWidthToggles dbcs_width_toggles(DbcsCodepage codepage) noexcept {",
        "  switch (codepage) {",
    ]
    for key, points in table.items():
        enum = CODEPAGES[key]
        lines += [
            f"    case DbcsCodepage::{enum}:",
            f"      return {{k{key.capitalize()}Toggles, sizeof(k{key.capitalize()}Toggles) / sizeof(std::uint16_t)}};",
        ]
    lines += [
        "    default:",
        "      return {nullptr, 0};",
        "  }",
        "}",
        "",
        "}  // namespace eval",
        "}  // namespace formulon",
        "",
    ]
    return "\n".join(lines)


def build() -> dict[str, list[int]]:
    data = json.loads(RUNS_PATH.read_text())
    unknown = set(data) - set(CODEPAGES)
    if unknown:
        raise SystemExit(f"unknown code page keys: {sorted(unknown)}")
    return {key: toggles(data[key]) for key in CODEPAGES if key in data}


def verify_probe(table: dict[str, list[int]], probe_dir: Path) -> int:
    failures = 0
    for key, points in table.items():
        sweep = json.loads((probe_dir / f"lenb_{PROBE_LOCALES[key]}.json").read_text())
        checked = 0
        for cp, width in zip(sweep["cps"], sweep["lenb"]):
            if width == -1:
                continue
            checked += 1
            if cp <= 0x7F and width != 1 or width_at(points, cp) != width:
                failures += 1
                print(f"{key}: U+{cp:04X} measured {width}, table {width_at(points, cp)}", file=sys.stderr)
        print(f"{key}: {checked} code points checked")
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare the output with the tracked file")
    parser.add_argument("--verify-probe", type=Path, help="directory of full LENB sweeps to verify against")
    args = parser.parse_args(argv)
    table = build()
    if args.verify_probe:
        return 1 if verify_probe(table, args.verify_probe) else 0
    text = render(table)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != text:
            print(f"{OUTPUT_PATH} is stale. {REGENERATION_GUIDANCE}", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
