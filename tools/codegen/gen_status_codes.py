#!/usr/bin/env python3
"""Generate the status-code tables from ``FormulonErrorCode`` in src/utils/error.h.

Outputs (all derived from the enum, never edited by hand):

* ``src/c_api/formulon_status.h``: ``#define FM_STATUS_<NAME> (<value>)`` per code.
* ``src/c_api/binding_status.h``: the generated region holding ``status_name``.
* ``packages/npm/common.mjs``: the ``StatusCode`` table (generated region).
* ``src/wasm/formulon.d.ts`` and ``packages/npm-native/index.d.ts``: the
  ``StatusCode`` declaration (generated region).
* ``packages/python/formulon/_status.py``: ``StatusCode`` and the exception
  family tables.

``<NAME>`` is the enumerator without its ``k`` prefix, split into words at
every lowercase-to-uppercase boundary (digits never start a word) and
upper-cased: ``kParserInvalidR1C1`` -> ``PARSER_INVALID_R1C1``. The
JavaScript key is the enumerator without ``k`` (``ParserInvalidR1C1``).

Modes:
  (default)       rewrite the outputs
  --check         exit 1 when an output differs from what would be generated
  --check-header  exit 1 when ``formulon_c.h`` still spells an enumerator
                  as ``kX`` instead of ``FM_STATUS_X`` in its documentation
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]
ERROR_H = REPO_ROOT / "src/utils/error.h"
C_HEADER = REPO_ROOT / "src/c_api/formulon_c.h"
STATUS_H = REPO_ROOT / "src/c_api/formulon_status.h"
BINDING_STATUS_H = REPO_ROOT / "src/c_api/binding_status.h"
NPM_COMMON = REPO_ROOT / "packages/npm/common.mjs"
WASM_DTS = REPO_ROOT / "src/wasm/formulon.d.ts"
NODE_DTS = REPO_ROOT / "packages/npm-native/index.d.ts"
PY_STATUS = REPO_ROOT / "packages/python/formulon/_status.py"

BEGIN = "// <status-codes:begin> generated by tools/codegen/gen_status_codes.py; do not edit"
END = "// <status-codes:end>"

# Codes whose "not found" meaning is not a lookup miss in the model.
NOT_FOUND_EXCLUDED = ("IO_FILE_NOT_FOUND", "CLI_FILE_NOT_FOUND")
# Codes outside the `_NOT_FOUND` suffix rule that still map to NotFoundError.
NOT_FOUND_EXTRA = ("SHEET_INDEX_OUT_OF_RANGE",)

Code = Tuple[str, str, int]  # (enumerator without k, UPPER_SNAKE, value)


def parse_codes() -> List[Code]:
    text = ERROR_H.read_text(encoding="utf-8")
    start = text.index("enum class FormulonErrorCode")
    body = text[start : text.index("};", start)]
    codes: List[Code] = []
    for match in re.finditer(r"^\s*k(\w+)\s*=\s*(\d+),", body, re.M):
        camel, value = match.group(1), int(match.group(2))
        codes.append((camel, upper_snake(camel), value))
    names = [c[1] for c in codes]
    values = [c[2] for c in codes]
    if len(set(names)) != len(names) or len(set(values)) != len(values):
        raise SystemExit("gen_status_codes: duplicate status name or value in error.h")
    return codes


def upper_snake(camel: str) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "_", camel).upper()


def not_found_names(codes: List[Code]) -> List[str]:
    out = []
    for _, name, _ in codes:
        if name in NOT_FOUND_EXCLUDED:
            continue
        if name == "NOT_FOUND" or name in NOT_FOUND_EXTRA or name.endswith("_NOT_FOUND"):
            out.append(name)
    return out


def render_status_h(codes: List[Code]) -> str:
    lines = [
        "// Status codes returned by the C ABI (`fm_status_t`).",
        "//",
        "// Generated by tools/codegen/gen_status_codes.py from `FormulonErrorCode`",
        "// in src/utils/error.h; do not edit.",
        "",
        "#ifndef FORMULON_C_API_FORMULON_STATUS_H_",
        "#define FORMULON_C_API_FORMULON_STATUS_H_",
        "",
    ]
    for _, name, value in codes:
        lines.append(f"#define FM_STATUS_{name} ({value})")
    lines += ["", "#endif  // FORMULON_C_API_FORMULON_STATUS_H_", ""]
    return "\n".join(lines)


def render_name_region(codes: List[Code]) -> str:
    lines = [
        BEGIN,
        "/// Returns the `FM_STATUS_<NAME>` spelling of a known status, or `nullptr`.",
        "inline const char* status_name(std::int32_t status) {",
        "  switch (status) {",
    ]
    for _, name, _ in codes:
        lines.append(f"    case FM_STATUS_{name}:")
        lines.append(f'      return "{name}";')
    lines += ["    default:", "      return nullptr;", "  }", "}", END]
    return "\n".join(lines)


def render_js_region(codes: List[Code]) -> str:
    lines = [BEGIN, "export const StatusCode = Object.freeze({"]
    lines += [f"  {camel}: {value}," for camel, _, value in codes]
    lines += ["});", END]
    return "\n".join(lines)


def render_dts_region(codes: List[Code]) -> str:
    lines = [
        BEGIN,
        "/** Engine status codes. Mirrors `fm_status_t` (`FM_STATUS_<NAME>`); each key is the",
        " *  code name in PascalCase. */",
        "export const StatusCode: Readonly<{",
    ]
    lines += [f"  {camel}: {value};" for camel, _, value in codes]
    lines += ["}>;", "/** Union of the {@link StatusCode} values. */", "export type StatusCode ="]
    lines += [f"  | {value}" for _, _, value in codes]
    lines[-1] += ";"
    lines.append(END)
    return "\n".join(lines)


def render_py(codes: List[Code]) -> str:
    not_found = set(not_found_names(codes))
    lines = [
        '"""Status codes of the Formulon C ABI.',
        "",
        "Generated by tools/codegen/gen_status_codes.py from ``FormulonErrorCode``",
        "in src/utils/error.h; do not edit.",
        '"""',
        "",
        "from enum import IntEnum",
        "",
        "",
        "class StatusCode(IntEnum):",
        '    """Engine status codes; the members are the ``FM_STATUS_<NAME>`` values."""',
        "",
    ]
    lines += [f"    {name} = {value}" for _, name, value in codes]
    lines += [
        "",
        "",
        "# Codes raised as `NotFoundError`.",
        "NOT_FOUND_CODES = frozenset(",
        "    (",
    ]
    lines += [f"        StatusCode.{name}," for _, name, _ in codes if name in not_found]
    lines += ["    )", ")", ""]
    return "\n".join(lines)


def splice(path: Path, region: str) -> str:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"gen_status_codes: no generated region markers in {path.relative_to(REPO_ROOT)}")
    return pattern.sub(lambda _: region, text, count=1)


def render_all() -> Dict[Path, str]:
    codes = parse_codes()
    return {
        STATUS_H: render_status_h(codes),
        BINDING_STATUS_H: splice(BINDING_STATUS_H, render_name_region(codes)),
        NPM_COMMON: splice(NPM_COMMON, render_js_region(codes)),
        WASM_DTS: splice(WASM_DTS, render_dts_region(codes)),
        NODE_DTS: splice(NODE_DTS, render_dts_region(codes)),
        PY_STATUS: render_py(codes),
    }


def read_or_empty(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def check_header() -> int:
    codes = parse_codes()
    text = C_HEADER.read_text(encoding="utf-8")
    alternation = "|".join(sorted((f"k{c[0]}" for c in codes), key=len, reverse=True))
    stale = sorted({m.group(0) for m in re.finditer(rf"\b(?:{alternation})\b", text)})
    if stale:
        print(
            f"gen_status_codes: formulon_c.h still names status codes as kX: {', '.join(stale)}",
            file=sys.stderr,
        )
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when generated outputs are out of date")
    mode.add_argument("--check-header", action="store_true", help="fail when formulon_c.h docs use kX names")
    args = parser.parse_args()

    if args.check_header:
        return check_header()

    outputs = render_all()
    if args.check:
        drift = [p for p, content in outputs.items() if read_or_empty(p) != content]
        for path in drift:
            print(
                f"gen_status_codes: {path.relative_to(REPO_ROOT)} is out of date; "
                "run tools/codegen/gen_status_codes.py",
                file=sys.stderr,
            )
        return 1 if drift else 0

    for path, content in outputs.items():
        if read_or_empty(path) != content:
            path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
