# ---------------------------------------------------------------------------
# File writer
# ---------------------------------------------------------------------------


def _clang_format(content: str, path: Path) -> str:
    """Pipe `content` through clang-format using `path`'s filename for style detection.

    Ensures generated files agree with the project-wide format-check (which
    runs `clang-format --dry-run --Werror` over `src/`). Falls back to the
    raw content if clang-format is unavailable, so a stripped CI image can
    still run the generator's --check mode against a previously-formatted
    snapshot.
    """
    cf = shutil.which("clang-format")
    if cf is None:
        return content
    proc = subprocess.run(
        [cf, f"--assume-filename={path.name}"],
        input=content,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        sys.stderr.write(
            f"clang-format failed on {path.name}: {proc.stderr}\n"
            "falling back to raw codegen output\n"
        )
        return content
    return proc.stdout


def _write_if_changed(path: Path, content: str) -> bool:
    """Write `content` to `path` only if it differs. Returns True on write."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == content:
        return False
    path.write_text(content)
    return True


def main(argv: List[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate binding glue from the YAML manifest.")
    p.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    p.add_argument("--out-c-api", type=Path, default=DEFAULT_OUT_CAPI)
    p.add_argument("--out-embind", type=Path, default=DEFAULT_OUT_EMBIND)
    p.add_argument("--out-node", type=Path, default=DEFAULT_OUT_NODE)
    p.add_argument(
        "--check",
        action="store_true",
        help="Do not write files; exit non-zero if any output would change.",
    )
    args = p.parse_args(argv)

    version, entries = _load_manifest(args.manifest)
    if version != 1:
        sys.stderr.write(f"manifest schema version {version} is not supported (expected 1)\n")
        return 2

    capi_files = _emit_capi(entries)
    embind_files = _emit_embind(entries)
    node_files = _emit_node(entries)

    drift = False
    for name, content in sorted(capi_files.items()):
        target = args.out_c_api / name
        content = _clang_format(content, target)
        if args.check:
            if not target.exists() or target.read_text() != content:
                sys.stderr.write(f"drift: {target}\n")
                drift = True
        else:
            wrote = _write_if_changed(target, content)
            if wrote:
                sys.stdout.write(f"wrote {target}\n")
    for name, content in sorted(embind_files.items()):
        target = args.out_embind / name
        content = _clang_format(content, target)
        if args.check:
            if not target.exists() or target.read_text() != content:
                sys.stderr.write(f"drift: {target}\n")
                drift = True
        else:
            wrote = _write_if_changed(target, content)
            if wrote:
                sys.stdout.write(f"wrote {target}\n")
    for name, content in sorted(node_files.items()):
        target = args.out_node / name
        content = _clang_format(content, target)
        if args.check:
            if not target.exists() or target.read_text() != content:
                sys.stderr.write(f"drift: {target}\n")
                drift = True
        else:
            wrote = _write_if_changed(target, content)
            if wrote:
                sys.stdout.write(f"wrote {target}\n")

    if args.check and drift:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
