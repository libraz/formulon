#!/usr/bin/env python3
"""Generate packages/npm-native/index.d.ts from the WASM declarations.

Inputs:

* ``src/wasm/formulon.d.ts``: every declaration both npm packages share,
  the ``createFormulon`` entry point included; only its file header comment
  is WASM-specific and is replaced.
* ``packages/npm-native/dts-delta.d.ts``: the members only the native package
  has, as a ``Workbook`` interface (or, when empty, the ``{}`` type alias a
  formatter rewrites it to) whose members are appended to the shared one.

Modes:
  (default)  rewrite index.d.ts
  --check    exit 1 when index.d.ts differs from what would be generated
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]
WASM_DTS = REPO_ROOT / "src/wasm/formulon.d.ts"
DELTA_DTS = REPO_ROOT / "packages/npm-native/dts-delta.d.ts"
NODE_DTS = REPO_ROOT / "packages/npm-native/index.d.ts"

HEADER = """// TypeScript declarations for @libraz/formulon-native, the N-API binding.
//
// Generated by tools/codegen/gen_native_dts.py from src/wasm/formulon.d.ts (the
// declarations shared with @libraz/formulon) and packages/npm-native/dts-delta.d.ts
// (the members only this package has). Do not edit.
"""


class GenError(ValueError):
    """An input declaration file does not have the expected shape."""


def _block(text: str, open_index: int) -> int:
    """Index of the ``}`` closing the ``{`` at ``open_index``, ignoring braces in comments."""
    depth = 0
    i = open_index
    while i < len(text):
        if text.startswith("/*", i):
            i = text.index("*/", i) + 2
            continue
        if text.startswith("//", i):
            i = text.index("\n", i)
            continue
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise GenError("unbalanced braces")


def _interface_body(text: str, name: str, *, alias: bool = False) -> Tuple[int, int]:
    """Half-open range of the text between the braces of ``export interface <name>``, or with ``alias`` also of
    ``export type <name> = {``."""
    pattern = rf"^export interface {re.escape(name)}\b[^{{]*\{{"
    if alias:
        pattern += rf"|^export type {re.escape(name)}\s*=\s*\{{"
    match = re.search(pattern, text, re.M)
    if match is None:
        raise GenError(f"interface {name} not found")
    open_index = match.end() - 1
    return open_index + 1, _block(text, open_index)


def generate(wasm_text: str, delta_text: str) -> str:
    # Drop the WASM file header comment; the directives after it stay.
    shared = re.sub(r"\A(?://(?!/)[^\n]*\n)+\n", "", wasm_text)

    start, stop = _interface_body(delta_text, "Workbook", alias=True)
    delta_members = delta_text[start:stop].strip("\n")
    if delta_members.strip():
        wb_start, wb_stop = _interface_body(shared, "Workbook")
        wb_body = shared[wb_start:wb_stop].rstrip("\n")
        shared = shared[:wb_start] + wb_body + "\n\n" + delta_members + "\n" + shared[wb_stop:]

    # The usage example imports the package being declared.
    example = "import createFormulon from '@libraz/formulon';"
    if shared.count(example) != 1:
        raise GenError("createFormulon usage example import not found")
    shared = shared.replace(example, "import createFormulon from '@libraz/formulon-native';")

    return HEADER + "\n" + shared.rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when index.d.ts is not what would be generated")
    args = parser.parse_args()
    try:
        rendered = generate(WASM_DTS.read_text(encoding="utf-8"), DELTA_DTS.read_text(encoding="utf-8"))
    except (OSError, GenError) as exc:
        print(f"gen_native_dts: {exc}", file=sys.stderr)
        return 1
    current = NODE_DTS.read_text(encoding="utf-8") if NODE_DTS.exists() else None
    if args.check:
        if current != rendered:
            print("gen_native_dts: packages/npm-native/index.d.ts is out of date; run tools/codegen/gen_native_dts.py")
            return 1
        return 0
    if current != rendered:
        NODE_DTS.write_text(rendered, encoding="utf-8")
        print(f"generated {NODE_DTS.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
