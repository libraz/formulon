#!/usr/bin/env python3
"""Generates the simple (1:1) case-mapping tables behind UPPER, LOWER and PROPER.

Input:   tools/casemap/case_map.json, from Mac Excel's UPPER / LOWER / PROPER of
         every BMP code point (supplementary code points map to themselves):
           upper, lower     [code point, mapped code point] pairs. U+03A3 is
                            absent from `lower`: its result depends on context.
           proper_start     [code point, result] where PROPER's word-start
                            result differs from UPPER (letters) or the character.
           proper_mid       the same for a character inside a word, versus LOWER.
           letters          [first, last] runs of the characters PROPER treats as
                            part of a word.
Output:  src/utils/case_map_table.cpp

A map is stored as runs [first, last, delta, stride]: every `stride`-th code
point in first..last maps to code point + delta.

Usage:
    python3 tools/casemap/generate_case_map.py          # rewrite the output
    python3 tools/casemap/generate_case_map.py --check  # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA_PATH = REPO_ROOT / "tools" / "casemap" / "case_map.json"
OUTPUT_PATH = REPO_ROOT / "src" / "utils" / "case_map_table.cpp"
REGENERATION_GUIDANCE = "Regenerate with: python3 tools/casemap/generate_case_map.py"

MAPS = [
    ("kUpperRuns", "upper"),
    ("kLowerRuns", "lower"),
    ("kProperStartRuns", "proper_start"),
    ("kProperMidRuns", "proper_mid"),
]


def to_runs(pairs: list[list[int]]) -> list[tuple[int, int, int, int]]:
    """Greedy run packing: consecutive entries with one delta and one stride (1 or 2)."""
    runs: list[list[int]] = []  # first, last, delta, stride, count
    for cp, target in sorted(pairs):
        delta = target - cp
        if runs:
            first, last, run_delta, stride, count = runs[-1]
            if run_delta == delta:
                if count == 1 and cp - last in (1, 2):
                    runs[-1] = [first, cp, delta, cp - last, 2]
                    continue
                if count >= 2 and cp - last == stride:
                    runs[-1] = [first, cp, delta, stride, count + 1]
                    continue
        runs.append([cp, cp, delta, 1, 1])
    return [(r[0], r[1], r[2], r[3]) for r in runs]


def render(data: dict) -> str:
    total = sum(len(to_runs(data[key])) for _, key in MAPS)
    letters = data["letters"]
    lines = [
        "// GENERATED by tools/casemap/generate_case_map.py from tools/casemap/case_map.json; do not edit.",
        "// Simple (1:1) case-mapping runs and the word-letter ranges of the BMP.",
        f"// @size-budget: {max(1, (total * 8 + len(letters) * 4 + 1023) // 1024)} KB",
        "",
        "// clang-format off",
        '#include "utils/case_map_table.h"',
        "",
        "namespace formulon {",
        "namespace case_map {",
        "namespace {",
        "",
    ]
    for name, key in MAPS:
        runs = to_runs(data[key])
        lines.append(f"constexpr CaseRun {name}[] = {{")
        for first, last, delta, stride in runs:
            lines.append(f"    {{0x{first:04X}, 0x{last:04X}, {delta}, {stride}}},")
        lines += ["};", ""]
    lines.append("constexpr std::uint16_t kLetterRanges[] = {")
    for i in range(0, len(letters), 6):
        row = letters[i : i + 6]
        lines.append("    " + ", ".join(f"0x{a:04X}, 0x{b:04X}" for a, b in row) + ",")
    lines += ["};", "", "}  // namespace", ""]
    for name, _key in MAPS:
        accessor = {
            "kUpperRuns": "upper_runs",
            "kLowerRuns": "lower_runs",
            "kProperStartRuns": "proper_start_runs",
            "kProperMidRuns": "proper_mid_runs",
        }[name]
        lines += [
            f"CaseRuns {accessor}() noexcept {{",
            f"  return {{{name}, sizeof({name}) / sizeof(CaseRun)}};",
            "}",
            "",
        ]
    lines += [
        "LetterRanges letter_ranges() noexcept {",
        "  return {kLetterRanges, sizeof(kLetterRanges) / (2 * sizeof(std::uint16_t))};",
        "}",
        "",
        "}  // namespace case_map",
        "}  // namespace formulon",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare the output with the tracked file")
    args = parser.parse_args(argv)
    text = render(json.loads(DATA_PATH.read_text()))
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != text:
            print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is out of date. {REGENERATION_GUIDANCE}", file=sys.stderr)
            return 1
        return 0
    OUTPUT_PATH.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
