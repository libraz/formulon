#!/usr/bin/env python3
"""Generate the CHANGELOG's name migration table from ``tools/api/names.yaml``.

One Markdown table per surface (C, JavaScript, Python), each row a former name
and what replaces it:

* a rename (``was`` differs from the current name), records and fields included
  (a field as ``Record.field``); an enum member (``kind: constant`` with
  ``enum:``) as ``Enum.Member``, the enum spelled as it was before and as it is
  now;
* an op a handle class now publishes (``handle:``): the former name and the
  handle method reached through its parent's lookup
  (``addPivotField()`` -> ``ws.pivot(...).addField()``);
* a field with ``was_semantics: inverted`` says so after its new name (a flag
  whose ``true`` now means the opposite);
* a ``drop`` name, whether or not it was also renamed: removed, pointing at the
  ``list`` entry that absorbs it, at the op that replaces it, or at the entry it
  was an alias of, when the ledger names one; a ``drop.note`` replaces that pointer;
* a ``replaced_by`` type: folded into the type it names; an ``internal`` op
  with ``replaced_by``: the facade member that took it over. Any other
  ``internal`` op has no row.

The table lives in ``CHANGELOG.md`` between the two marker comments below, so
the generated rows and the hand-written notes around them never overlap.

Modes:
  (default)  print the table
  --write    replace the marked region of CHANGELOG.md with the table
  --check    exit 1 when the marked region differs from the table, or is missing
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "tools" / "dev"))

from binding_drift.api_conventions import (  # noqa: E402
    common_base,
    entry_handle,
    handle_bases,
    handle_classes,
    handle_name,
)
from check_changelog_identifiers import previous_release, released_names  # noqa: E402

LEDGER_PATH = REPO_ROOT / "tools" / "api" / "names.yaml"
CHANGELOG = REPO_ROOT / "CHANGELOG.md"
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")

BEGIN = "<!-- migration-table:begin generated by tools/api/gen_migration_table.py; do not edit -->"
END = "<!-- migration-table:end -->"

SURFACES = (
    ("c", "C ABI"),
    ("js", "JavaScript (`@libraz/formulon`, `@libraz/formulon-native`)"),
    ("py", "Python (`formulon`)"),
)

Row = Tuple[str, str]
# The receiver each binding class is reached through in the rows.
_RECEIVERS = {"workbook": "wb", "sheet": "ws"}


def load_ledger(path: Path = LEDGER_PATH) -> dict:
    import yaml  # type: ignore

    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema") != 1 or not isinstance(data.get("entries"), dict):
        raise SystemExit(f"gen_migration_table: {path} is not a `schema: 1` ledger")
    return data


def _call(name: str, field: str, kind: str) -> str:
    """A name as it is written in code: functions get `()`, types and fields do not."""
    if field == "c" or kind in ("record", "enum", "typedef", "constant", "field"):
        return f"`{name}`"
    return f"`{name}()`"


def _absorbing_list(data: dict, key: str, field: str) -> Optional[str]:
    """How the list that absorbs the op `key` is written now, handle method included."""
    for list_key, entry in data["entries"].items():
        if isinstance(entry, dict) and entry.get("kind") == "list" and key in (entry.get("from") or []):
            if isinstance(entry.get(field), str):
                return _target_call(data, list_key, field)
    return None


def _parent_name(entries: Dict[str, dict], key: str, field: str) -> Optional[str]:
    parts = key.split(".")
    while len(parts) > 1:
        parts.pop()
        parent = entries.get(".".join(parts))
        if isinstance(parent, dict) and isinstance(parent.get(field), str):
            return parent[field]
    return None


def _snake(name: str) -> str:
    return "".join(f"_{c.lower()}" if c.isupper() else c for c in name).lstrip("_")


def _accessor(data: dict, cls: str, field: str) -> str:
    """How a handle of `cls` is reached: `wb.sheet(...)`, `ws.pivot(...)`, `wb.table(...)`, ..."""
    if cls == "Sheet":
        return "wb.sheet(...)"
    lookup = cls[:1].lower() + cls[1:]
    name = lookup if field == "js" else _snake(lookup)
    scope = "sheet"
    for coll in (data.get("collections") or {}).values():
        if isinstance(coll, dict) and coll.get("handle_class") == cls:
            for op in coll.get("ops") or []:
                entry = data["entries"].get(op) or {}
                if entry.get(field) == name:
                    scope = entry.get("scope", scope)
    return f"{_RECEIVERS.get(scope, 'ws')}.{name}(...)"


def _handle_call(data: dict, entry: dict, field: str) -> Optional[str]:
    """`ws.pivot(...).addField()` for an op a handle class publishes, else None."""
    if field == "c":
        return None
    handle = entry_handle(entry)
    name = handle_name(entry, field, data.get("collections") or {}) if handle is not None else None
    if not name:
        return None
    cls = common_base(handle_classes(entry), handle_bases(data.get("collections") or {}))
    suffix = "" if handle.get("property") is True else "()"
    return f"`{_accessor(data, cls, field)}.{name}{suffix}`"


def _target_call(data: dict, key: str, field: str) -> Optional[str]:
    """How the op `key` is written now: its handle method, else its current name."""
    entry = data["entries"].get(key)
    if not isinstance(entry, dict):
        return None
    handled = _handle_call(data, entry, field)
    if handled:
        return handled
    name = entry.get(field)
    return _call(name, field, str(entry.get("kind", ""))) if isinstance(name, str) else None


def _owner_names(entries: Dict[str, dict], key: str, field: str) -> Tuple[str, str]:
    """The `Enum.` prefix of an enum member, before and after: the enum's former and current name."""
    owner = entries.get(key)
    if not isinstance(owner, dict):
        return "", ""
    now = owner.get(field)
    was = (owner.get("was") or {}).get(field) if isinstance(owner.get("was"), dict) else None
    after = f"{now}." if isinstance(now, str) else ""
    before = f"{was}." if isinstance(was, str) else after
    return before, after


def rows(data: dict) -> Dict[str, List[Row]]:
    """Per name field (`c` / `js` / `py`), the (before, after) cells."""
    entries: Dict[str, dict] = data["entries"]
    out: Dict[str, List[Row]] = {field: [] for field, _ in SURFACES}
    for key, entry in entries.items():
        if not isinstance(entry, dict):
            continue
        kind = str(entry.get("kind", ""))
        was = entry.get("was") if isinstance(entry.get("was"), dict) else {}
        drop = entry.get("drop") if isinstance(entry.get("drop"), dict) else {}
        for field, _title in SURFACES:
            old = was.get(field)
            if not isinstance(old, str):
                # A name that kept its spelling but was removed from this surface.
                old = drop.get(field) if kind != "field" else None
                if not isinstance(old, str) or entry.get(field) != old:
                    continue
            if kind == "constant" and "enum" in entry and field != "c":
                before_owner, after_owner = _owner_names(entries, str(entry["enum"]), field)
                new = entry.get(field)
                if isinstance(new, str) and new != old:
                    out[field].append((f"`{before_owner}{old}`", f"`{after_owner}{new}`"))
                elif isinstance(drop.get(field), str):
                    out[field].append((f"`{before_owner}{old}`", "removed"))
                continue
            if kind == "field":
                before_owner, after_owner = _owner_names(entries, str(entry.get("record")), field)
                new = entry.get(field)
                if isinstance(new, str) and new != old:
                    after = f"`{after_owner}{new}`"
                    if entry.get("was_semantics") == "inverted":
                        after += "; inverted: `true` allows what the former flag prevented"
                    out[field].append((f"`{before_owner}{old}`", after))
                continue
            # An op or list a facade member took over keeps its C function unless the ledger drops it.
            replaced = "replaced_by" in entry and not (
                kind in ("op", "list") and field == "c" and not isinstance(drop.get("c"), str)
            )
            if replaced and kind in ("op", "list"):
                instead = _target_call(data, str(entry["replaced_by"]), field)
                if entry.get("internal") is True:
                    after = instead or "removed"
                else:
                    after = f"removed; use {instead}" if instead else "removed"
                out[field].append((_call(old, field, kind), after))
                continue
            if replaced:
                target = entries.get(str(entry["replaced_by"]), {})
                new = target.get(field) if isinstance(target, dict) else None
                dropped = isinstance(target, dict) and (target.get("drop") or {}).get(field) == new
                after = f"folded into `{new}`" if isinstance(new, str) and not dropped else "removed"
                out[field].append((_call(old, field, kind), after))
                continue
            if entry.get("internal") is True and field != "c":
                continue
            # A dropped op with no name left has no handle method either.
            dropped = isinstance(drop.get(field), str) and not isinstance(entry.get(field), str)
            handled = None if dropped else _handle_call(data, entry, field)
            if handled:
                out[field].append((_call(old, field, kind), handled))
                continue
            if isinstance(drop.get(field), str):
                listed = _absorbing_list(data, key, field)
                parent = _parent_name(entries, key, field)
                instead = listed or (_call(parent, field, "op") if parent else None)
                after = f"removed; use {instead}" if instead else "removed"
                if isinstance(drop.get("note"), str):
                    after = f"removed; {drop['note']}"
                out[field].append((_call(old, field, kind), after))
                continue
            new = entry.get(field)
            if isinstance(new, str) and new != old:
                out[field].append((_call(old, field, kind), _call(new, field, kind)))
    for field in out:
        out[field] = sorted(set(out[field]), key=lambda r: r[0].lower())
    return out


def render(data: dict, released: Optional[Set[str]] = None) -> str:
    """The tables; with ``released``, only rows whose former name the previous release shipped."""
    table = rows(data)
    if released is not None:
        table = {f: [r for r in rs if set(IDENT.findall(r[0])) <= released] for f, rs in table.items()}
    parts: List[str] = []
    for field, title in SURFACES:
        if not table[field]:
            continue
        parts.append(f"#### {title}\n\n| Before | After |\n|---|---|\n")
        parts.append("".join(f"| {before} | {after} |\n" for before, after in table[field]))
        parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


def _region(text: str) -> Optional[Tuple[int, int]]:
    start = text.find(BEGIN)
    end = text.find(END, start + len(BEGIN)) if start >= 0 else -1
    if start < 0 or end < 0:
        return None
    return start + len(BEGIN), end


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ledger", type=Path, default=LEDGER_PATH)
    parser.add_argument("--changelog", type=Path, default=CHANGELOG)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="replace the marked CHANGELOG region")
    mode.add_argument("--check", action="store_true", help="fail when the marked CHANGELOG region is stale")
    args = parser.parse_args(argv)
    released = released_names(previous_release(args.changelog.read_text(encoding="utf-8")))
    body = "\n" + render(load_ledger(args.ledger), released)
    if not (args.write or args.check):
        sys.stdout.write(body.lstrip("\n"))
        return 0
    text = args.changelog.read_text(encoding="utf-8")
    span = _region(text)
    if span is None:
        print(f"gen_migration_table: {args.changelog.name} has no `{BEGIN}` ... `{END}` region")
        return 1
    current = text[span[0] : span[1]]
    if args.check:
        if current != body:
            print(f"gen_migration_table: the migration table in {args.changelog.name} differs from the ledger")
            return 1
        print("gen_migration_table: the migration table matches the ledger")
        return 0
    args.changelog.write_text(text[: span[0]] + body + text[span[1] :], encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
