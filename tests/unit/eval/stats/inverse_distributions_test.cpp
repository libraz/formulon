TEST(InverseDistributions, GammaFamilyMatchesExcelValues) {
  for (const Pair& q : kGammaInv) {
    EXPECT_EQ(gamma_inv_excel(q.p, q.a, q.b), q.value) << q.p << " " << q.a << " " << q.b;
  }
  for (const Single& q : kChisqInv) {
    EXPECT_EQ(chisq_inv_excel(q.p, q.df, false), q.value) << q.p << " " << q.df;
  }
  for (const Single& q : kChisqInvRt) {
    EXPECT_EQ(chisq_inv_excel(q.p, q.df, true), q.value) << q.p << " " << q.df;
  }
}

TEST(InverseDistributions, GammaNegativeInitialGuessIsNaN) {
  EXPECT_TRUE(std::isnan(gamma_inv_excel(0.999, 0.001, 1.0)));
  EXPECT_TRUE(std::isnan(gamma_inv_excel(0.999999, 0.001, 0.001)));
  EXPECT_TRUE(std::isnan(gamma_inv_excel(0.999999999999999, 0.001, 1.0)));
}

TEST(InverseDistributions, BetaFamilyMatchesExcelValues) {
  for (const Pair& q : kBetaInv) {
    EXPECT_EQ(beta_inv_excel(q.p, q.a, q.b, 0.0, 1.0), q.value) << q.p << " " << q.a << " " << q.b;
  }
  for (const Single& q : kTInv) {
    EXPECT_EQ(t_inv_excel(q.p, q.df), q.value) << q.p << " " << q.df;
  }
  for (const Pair& q : kFInv) {
    EXPECT_EQ(f_inv_excel(q.p, q.a, q.b, false), q.value) << q.p << " " << q.a << " " << q.b;
  }
  for (const Pair& q : kFInvRt) {
    EXPECT_EQ(f_inv_excel(q.p, q.a, q.b, true), q.value) << q.p << " " << q.a << " " << q.b;
  }
}

TEST(InverseDistributions, BinomialQuantile) {
  EXPECT_EQ(binom_inv_excel(10.0, 0.5, 0.5), 5.0);
  EXPECT_EQ(binom_inv_excel(10.0, 0.5, 0.0009), 0.0);
  EXPECT_EQ(binom_inv_excel(10.0, 0.5, 0.9995), 10.0);
}

TEST(InverseDistributions, Median) {
  EXPECT_EQ(t_inv_excel(0.5, 7.0), 0.0);
}

