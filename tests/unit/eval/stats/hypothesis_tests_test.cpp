TEST(HypothesisTestsExcel, TTestMatchesExcelValues) {
  for (const TTestCase& c : kTTests) {
    const TestOutcome r =
        c.type == 1 ? t_test_paired_excel(c.x.data(), c.y.data(), c.x.size(), c.tails)
                    : t_test_two_sample_excel(c.x.data(), c.x.size(), c.y.data(), c.y.size(), c.tails, c.type);
    ASSERT_FALSE(r.div0);
    EXPECT_EQ(r.p, c.value) << "tails " << c.tails << " type " << c.type;
  }
}

TEST(HypothesisTestsExcel, ConstantSamplesAreDivisionByZero) {
  const double a[] = {2.0, 2.0, 2.0};
  const double b[] = {5.0, 5.0, 5.0};
  EXPECT_TRUE(t_test_paired_excel(a, b, 3, 2).div0);
  EXPECT_TRUE(t_test_two_sample_excel(a, 3, b, 3, 2, 2).div0);
  EXPECT_TRUE(f_test_excel(a, 3, b, 3).div0);
  const double one[] = {1.0};
  EXPECT_TRUE(f_test_excel(one, 1, b, 3).div0);
}

TEST(HypothesisTestsExcel, FTestIsSymmetric) {
  const double a[] = {1.0, 4.0, 9.0, 2.5, 7.0};
  const double b[] = {3.0, 3.5, 4.0, 3.2, 3.9, 4.4};
  const TestOutcome ab = f_test_excel(a, 5, b, 6);
  ASSERT_FALSE(ab.div0);
  EXPECT_GT(ab.p, 0.0);
  EXPECT_LT(ab.p, 1.0);
  EXPECT_NEAR(ab.p, f_test_excel(b, 6, a, 5).p, 1e-12);
}

TEST(HypothesisTestsExcel, ChisqTestProbability) {
  EXPECT_EQ(chisq_test_p_excel(0.0, 4.0), 1.0);
  double stat = 0.0;
  stat = chisq_accumulate_excel(stat, 12.0, 10.0);
  stat = chisq_accumulate_excel(stat, 8.0, 10.0);
  EXPECT_NEAR(stat, 0.8, 1e-15);
  EXPECT_NEAR(chisq_test_p_excel(stat, 1.0), 0.37109336952269745, 1e-12);
}

TEST(HypothesisTestsExcel, ConfidenceHalfWidths) {
  EXPECT_NEAR(confidence_norm_excel(0.05, 100.0, 100.0), 19.59963984540054, 1e-12);
  EXPECT_NEAR(confidence_t_excel(0.05, 20.0, 30.0), 7.468122735161993, 1e-12);
}

