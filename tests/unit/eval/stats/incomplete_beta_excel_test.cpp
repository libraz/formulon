TEST(IncompleteBetaExcel, BetaCdfMatchesExcelValues) {
  for (const PointAb& p : kBetaCdf) {
    EXPECT_EQ(beta_ratio_excel(p.a, p.b, p.x, false), p.value) << p.a << " " << p.b << " " << p.x;
  }
}

TEST(IncompleteBetaExcel, BetaPdfMatchesExcelValues) {
  for (const PointAb& p : kBetaPdf) {
    EXPECT_EQ(beta_dist_pdf_excel(p.x, p.a, p.b, 0.0, 1.0), p.value) << p.a << " " << p.b << " " << p.x;
  }
}

TEST(IncompleteBetaExcel, FDistributionMatchesExcelValues) {
  for (const PointAb& p : kFCdf) {
    EXPECT_EQ(f_dist_cdf_excel(p.x, p.a, p.b, false), p.value) << p.a << " " << p.b << " " << p.x;
  }
  for (const PointAb& p : kFRt) {
    EXPECT_EQ(f_dist_cdf_excel(p.x, p.a, p.b, true), p.value) << p.a << " " << p.b << " " << p.x;
  }
}

TEST(IncompleteBetaExcel, TDistributionMatchesExcelValues) {
  for (const PointDf& p : kTCdf) {
    EXPECT_EQ(t_dist_tail_excel(p.x, p.df, false), p.value) << p.df << " " << p.x;
  }
  for (const PointDf& p : kTRt) {
    EXPECT_EQ(t_dist_tail_excel(p.x, p.df, true), p.value) << p.df << " " << p.x;
  }
  for (const PointDf& p : kT2t) {
    EXPECT_EQ(t_dist_2t_excel(std::fabs(p.x), p.df), p.value) << p.df << " " << p.x;
  }
  for (const PointDf& p : kTPdf) {
    EXPECT_EQ(t_dist_pdf_excel(p.x, p.df), p.value) << p.df << " " << p.x;
  }
}

TEST(IncompleteBetaExcel, Boundaries) {
  EXPECT_EQ(beta_ratio_excel(2.0, 3.0, 0.0, false), 0.0);
  EXPECT_EQ(beta_ratio_excel(2.0, 3.0, 1.0, false), 1.0);
  EXPECT_EQ(beta_ratio_excel(2.0, 3.0, 0.4, false) + beta_ratio_excel(2.0, 3.0, 0.4, true), 1.0);
  EXPECT_EQ(beta_ratio_excel(1.0, 1.0, 0.25, false), 0.25);
  EXPECT_EQ(binom_cdf_excel(5.0, 5.0, 0.3), 1.0);
  EXPECT_EQ(binom_cdf_excel(-1.0, 5.0, 0.3), 0.0);
  EXPECT_EQ(hypgeom_cdf_excel(0.0, 2.0, 3.0, 10.0) + 0.0, hypgeom_pmf_excel(0.0, 2.0, 3.0, 10.0));
}

