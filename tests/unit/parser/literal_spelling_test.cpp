TEST(SpellNumberLiterals, OnlyTheTouchingUnarySignIsAbsorbed) {
  EXPECT_EQ(spell_number_literals("=1-5"), "=1-5");
  EXPECT_EQ(spell_number_literals("=1+5"), "=1+5");
  EXPECT_EQ(spell_number_literals("=A1-0"), "=A1-0");
  EXPECT_EQ(spell_number_literals("=(1)-0"), "=(1)-0");
  EXPECT_EQ(spell_number_literals("=5%-0"), "=5%-0");
  EXPECT_EQ(spell_number_literals("=\"a\"&+5"), "=\"a\"&5");
  EXPECT_EQ(spell_number_literals("=1 -0"), "=1 -0");
  EXPECT_EQ(spell_number_literals("=1+ -0"), "=1+ 0");
}

TEST(SpellNumberLiterals, WhitespaceIsKeptAndBlocksAbsorption) {
  EXPECT_EQ(spell_number_literals("=- 1.50"), "=- 1.5");
  EXPECT_EQ(spell_number_literals("= 1.50 + 2.0 "), "= 1.5 + 2 ");
  EXPECT_EQ(spell_number_literals("=sum( +1.0 )"), "=sum( 1 )");
}

TEST(SpellNumberLiterals, NonLiteralTextIsUntouched) {
  EXPECT_EQ(spell_number_literals("=\"1.50\"&\"-0\""), "=\"1.50\"&\"-0\"");
  EXPECT_EQ(spell_number_literals("=SUM(1:03)"), "=SUM(1:03)");
  EXPECT_EQ(spell_number_literals("=SUM($1:$3)+1.0"), "=SUM($1:$3)+1");
  EXPECT_EQ(spell_number_literals("=Table1[[#This Row],[1.50]]+1.0"), "=Table1[[#This Row],[1.50]]+1");
  EXPECT_EQ(spell_number_literals("='2024'!A1+1.0"), "='2024'!A1+1");
  EXPECT_EQ(spell_number_literals("=LOG10(1.0E2)"), "=LOG10(100)");
}

TEST(SpellNumberLiterals, LeadingEqualSignIsOptional) {
  EXPECT_EQ(spell_number_literals("+1.50"), "1.5");
  EXPECT_EQ(spell_number_literals("1-+5"), "1-5");
  EXPECT_EQ(spell_number_literals(""), "");
  EXPECT_EQ(spell_number_literals("="), "=");
}

TEST(SpellNumberLiterals, RejectedRunsAreLeftAlone) {
  EXPECT_EQ(spell_number_literals("=-1E-310+1.50"), "=-1E-310+1.5");
  EXPECT_EQ(spell_number_literals("=1.50+\"open"), "=1.5+\"open");
}

TEST(SpellNumberLiterals, IdempotentOnTextWithoutASurvivingTouchingSign) {
  const std::vector<std::string_view> stored = {
      "=1.5",
      "=1000",
      "=1E+21",
      "=-1E+21",
      "=0.0000000000000000001",
      "={5,0,1.5}",
      "=-5",
      "=--5",
      "=+-5",
      "=-+-5",
      "=1+ 5",
      "=- 5",
      "=-(0)",
      "=SUM(0,1)",
      "=1-5",
      "=1.2345E-18",
      "=1.23456789012345E+69",
      "=-5^2",
      "=5%",
      "=+A1",
      "=-\"5\"",
      "=+{1,2}+1",
      "=-0.5",
      "=0-0",
  };
  for (const std::string_view text : stored) {
    EXPECT_EQ(spell_number_literals(text), text) << text;
  }
}

TEST(SpellNumberLiterals, SurvivingTouchingSignIsAbsorbedOnReentry) {
  EXPECT_EQ(spell_number_literals(spell_number_literals("=++5")), "=5");
  EXPECT_EQ(spell_number_literals(spell_number_literals("=--0")), "=0");
}

