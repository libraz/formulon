TEST(XlsbParityProtectedRange, EncodesAndReadsShapesAsExcelSavedThem) {
  for (const ExcelSavedShape& shape : kExcelSavedShapes) {
    SCOPED_TRACE(shape.sddl);
    const Bytes excel = FromHex(shape.hex);
    Bytes sd;
    ASSERT_EQ(encode_security_descriptor(shape.sddl, sd), shape.status);
    if (shape.status == SddlEncode::kEncoded) {
      EXPECT_EQ(sd, excel);
    }
    // The text kept for the range is the one Excel writes to xlsx.
    EXPECT_EQ(canonical_security_descriptor(shape.sddl), shape.text == nullptr ? "" : shape.text);
    std::string text;
    if (!excel.empty() && decode_security_descriptor(ByteSpan{excel.data(), excel.size()}, text)) {
      ASSERT_NE(shape.text, nullptr);
      EXPECT_EQ(text, shape.text);
    }
  }
}

TEST(XlsbParityProtectedRange, KeepsTheDescriptorInTheSpellingExcelKeeps) {
  const std::pair<const char*, const char*> cases[] = {
      {"G:WDO:WDD:(A;;CC;;;WD)", "O:WDG:WDD:(A;;CC;;;WD)"},
      {"O:WDG:WDD:(OA;;CC;;;WD)", "O:WDG:WDD:"},
      {"O:DAG:DAD:(A;;CC;;;DA)", ""},
      {"o:wdg:wdd:(a;;cc;;;wd)", ""},
      {"O:WDG:WDD:P(A;;CC;;;WD)", "O:WDG:WDD:P(A;;CC;;;WD)"},
  };
  for (const auto& [given, kept] : cases) {
    SCOPED_TRACE(given);
    ProtectedRange range;
    range.name = "A";
    range.sqref = "A1";
    range.security_descriptor = given;
    // Stored through the model's one writer.
    WorksheetRawExtensions stored;
    write_protected_ranges(stored, {range});
    ASSERT_EQ(read_protected_ranges(stored).size(), 1U);
    EXPECT_EQ(read_protected_ranges(stored)[0].security_descriptor, kept);
    // Loaded as written by another producer: the reader re-spells it the same way.
    WorksheetRawExtensions loaded = stored;
    range.security_descriptor = "O:WDG:WDD:(A;;CC;;;WD)";
    WorksheetRawExtensions canonical;
    write_protected_ranges(canonical, {range});
    loaded[0].xml = canonical[0].xml;
    const std::size_t at = loaded[0].xml.find("O:WDG:WDD:(A;;CC;;;WD)");
    ASSERT_NE(at, std::string::npos);
    loaded[0].xml.replace(at, std::string_view("O:WDG:WDD:(A;;CC;;;WD)").size(), given);
    canonicalize_protected_ranges(loaded);
    EXPECT_EQ(read_protected_ranges(loaded)[0].security_descriptor, kept);
    // A loaded part already in that spelling is left byte for byte.
    const std::string before = canonical[0].xml;
    canonicalize_protected_ranges(canonical);
    EXPECT_EQ(canonical[0].xml, before);
  }
}

TEST(XlsbParityProtectedRange, RefusesSddlOutsideTheEncodedForm) {
  for (const char* sddl : {
           "",                                     // empty
           "O:WD",                                 // no group or DACL
           "O:WDD:G:WD",                           // a section order Excel was not seen to encode
           "O:WDG:WDO:WD",                         // a repeated section
           "O:WDD:(A;;CC;;;WD)",                   // no group
           "O:WDG:WDD:P(A;;CC;;;WD)",              // DACL flags
           "O:WDG:WDD:(A;;CC;;;WD)S:",             // SACL
           "O:WDG:WDD:(OA;;CC;;;WD)(A;;CC;;;WD)",  // an object ACE beside another ACE
           "O:WDG:WDD:(OA;;CC;;00000000-0000-0000-0000-000000000001;WD)",  // inherited object type
           "O:WDG:WDD:(A;CI;CC;;;WD)",                                     // ACE flags
           "O:WDG:WDD:(A;;0x;;;WD)",                                       // hex rights without digits
           "O:WDG:WDD:(A;;0x1GA;;;WD)",                                    // a hex mask mixed with a right token
           "O:WDG:WDD:(A;;;;;WD)",                                         // no rights
           "O:WDG:WDD:(A;;XX;;;WD)",                                       // unknown right
           "O:WDG:WDD:(A;;CC;;;WD",                                        // unterminated ACE
           "O:S-1-5-21-1-2-3-500G:WDD:",                                   // a SID literal that is no alias
           "O:WDG:WDS:",                                                   // unknown section
           "o:WDG:WDD:",                                                   // a lower-case section letter
           "O:WDG:WDD:(a;;CC;;;WD)",                                       // a lower-case ACE type
           "O:DAG:WDD:(A;;CC;;;WD)S:",                                     // a SACL, behind a domain-relative alias too
       }) {
    SCOPED_TRACE(sddl);
    Bytes sd;
    EXPECT_EQ(encode_security_descriptor(sddl, sd), SddlEncode::kUnsupported);
    EXPECT_TRUE(sd.empty());
  }
  for (const char* sddl :
       {"O:ZZG:WD", "O:WDG:ZZD:", "O:WDG:WDD:(A;;CC;;;ZZ)", "O:DAG:WDD:", "o:wdg:wdd:(a;;cc;;;wd)"}) {
    SCOPED_TRACE(sddl);
    Bytes sd;
    EXPECT_EQ(encode_security_descriptor(sddl, sd), SddlEncode::kMalformed);
  }
}

TEST(XlsbParityProtectedRange, DecodeRefusesOtherDescriptors) {
  Bytes sd;
  ASSERT_EQ(encode_security_descriptor("O:WDG:WDD:(A;;CC;;;WD)", sd), SddlEncode::kEncoded);
  std::string text;
  // Each single-byte change outside the ACE mask, and a trailing byte, leaves a descriptor of no measured form.
  for (std::size_t i = 0; i < sd.size(); ++i) {
    if (i >= 32U && i < 36U) {
      continue;
    }
    SCOPED_TRACE(i);
    Bytes changed = sd;
    changed[i] ^= 0x40U;
    EXPECT_FALSE(decode_security_descriptor(ByteSpan{changed.data(), changed.size()}, text));
  }
  Bytes longer(sd.size() + 1U, 0U);
  std::copy(sd.begin(), sd.end(), longer.begin());
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{longer.data(), longer.size()}, text));
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{sd.data(), 27U}, text));
  // A mask of no bits has no spelling.
  Bytes no_rights = sd;
  no_rights[32] = 0U;
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{no_rights.data(), no_rights.size()}, text));
  // A bare SID is not a descriptor of the encoded form (Restricted Code).
  const Bytes bare = Sid({5, 12});
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{bare.data(), bare.size()}, text));
  Bytes no_dacl;
  ASSERT_EQ(encode_security_descriptor("O:WDG:WD", no_dacl), SddlEncode::kEncoded);
  // A DACL offset without the control bit, and the control bit without an offset.
  Bytes stray = no_dacl;
  stray[16] = 20U;
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{stray.data(), stray.size()}, text));
  Bytes missing = sd;
  missing[16] = 0U;
  EXPECT_FALSE(decode_security_descriptor(ByteSpan{missing.data(), missing.size()}, text));
}

