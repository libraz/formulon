TEST(XlsbParityProtectedRange, IsoPairWithDifferentDescriptorsIsKeptRaw) {
  Bytes sd;
  ASSERT_EQ(encode_security_descriptor("O:WDG:WDD:(A;;CC;;;WD)", sd), SddlEncode::kEncoded);
  const Bytes payload = RangeProtection(1U, "R", sd);
  Bytes iso;
  emit_u32(iso, 100000U);
  emit_u32(iso, 1U);
  emit_rfx(iso, MergeRange{0U, 0U, 0U, 0U});
  emit_xlwidestring(iso, "R");
  emit_u32(iso, 0U);  // no descriptor
  emit_u32(iso, 1U);
  iso.push_back(0xAAU);
  emit_u32(iso, 1U);
  iso.push_back(0x55U);
  emit_xlnullablewidestring(iso, std::string_view("SHA-512"));
  ProtectedRange out;
  EXPECT_EQ(decode_range_protection(ByteSpan{payload.data(), payload.size()}, ByteSpan{iso.data(), iso.size()}, out),
            RangeProtectionRead::kSecurityDescriptor);
}

