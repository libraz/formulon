Bytes FromHex(const std::string& hex) {
  Bytes out;
  for (std::size_t i = 0; i + 1U < hex.size(); i += 2U) {
    out.push_back(static_cast<std::uint8_t>(std::stoi(hex.substr(i, 2U), nullptr, 16)));
  }
  return out;
}

TEST(XlsbParityProtectedRange, EncodesAndReadsBackAsExcelDoes) {
  for (const MeasuredForm& form : kMeasuredForms) {
    SCOPED_TRACE(form.sddl);
    const Bytes expected = FromHex(form.hex);
    Bytes sd;
    ASSERT_EQ(encode_security_descriptor(form.sddl, sd), SddlEncode::kEncoded);
    EXPECT_EQ(sd, expected);
    std::string text;
    // A hex spelling ("0x...") is not emitted: the record stays raw.
    if (std::string_view(form.spelled).find("0x") != std::string_view::npos) {
      EXPECT_FALSE(decode_security_descriptor(ByteSpan{expected.data(), expected.size()}, text));
      continue;
    }
    ASSERT_TRUE(decode_security_descriptor(ByteSpan{expected.data(), expected.size()}, text));
    EXPECT_EQ(text, form.spelled[0] == '\0' ? form.sddl : form.spelled);
  }
}

