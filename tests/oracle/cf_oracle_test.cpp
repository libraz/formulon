// Loads and caches the CF golden document (parsed once per process). A
// missing or malformed golden is a test-rig error, not a per-case
// failure, so it surfaces via the accessor's ADD_FAILURE below rather
// than crashing every fixture.
const JsonValue& CfGolden() {
  static const JsonValue golden = [] {
    const std::string path = std::string(FORMULON_CF_GOLDEN_DIR) + "/cf_smoke.golden.json";
    auto parsed = ::formulon::tests::oracle::parse_json_file(path);
    if (!parsed.has_value()) {
      ADD_FAILURE() << "failed to load CF golden at " << path << ": " << parsed.error().message;
      return JsonValue::make_null();
    }
    return std::move(parsed).value();
  }();
  return golden;
}

// Returns the `cells` array for `case_id`, or nullptr if the case (or
// the golden document) is absent. The returned vector is owned by the
// process-lifetime static in CfGolden(), so the pointer stays valid.
const std::vector<JsonValue>* GoldenCellsFor(std::string_view case_id) {
  const JsonValue& root = CfGolden();
  if (!root.is_object()) {
    return nullptr;
  }
  const JsonValue* cases = root.find("cases");
  if (cases == nullptr || !cases->is_array()) {
    return nullptr;
  }
  for (const JsonValue& entry : cases->as_array()) {
    const JsonValue* id = entry.find("id");
    if (id != nullptr && id->is_string() && id->as_string() == case_id) {
      const JsonValue* cells = entry.find("cells");
      return (cells != nullptr && cells->is_array()) ? &cells->as_array() : nullptr;
    }
  }
  return nullptr;
}

std::optional<CFMatchKind> CFMatchKindFromString(const std::string& s) {
  if (s == "DifferentialFormat")
    return CFMatchKind::DifferentialFormat;
  if (s == "ColorScale")
    return CFMatchKind::ColorScale;
  if (s == "DataBar")
    return CFMatchKind::DataBar;
  if (s == "IconSet")
    return CFMatchKind::IconSet;
  return std::nullopt;
}

std::optional<IconSetName> IconSetNameFromString(const std::string& s) {
  static const std::map<std::string, IconSetName> kMap = {
      {"Three_Arrows", IconSetName::Three_Arrows},
      {"Three_ArrowsGray", IconSetName::Three_ArrowsGray},
      {"Three_Flags", IconSetName::Three_Flags},
      {"Three_TrafficLights1", IconSetName::Three_TrafficLights1},
      {"Three_TrafficLights2", IconSetName::Three_TrafficLights2},
      {"Three_Signs", IconSetName::Three_Signs},
      {"Three_Symbols", IconSetName::Three_Symbols},
      {"Three_Symbols2", IconSetName::Three_Symbols2},
      {"Four_Arrows", IconSetName::Four_Arrows},
      {"Four_ArrowsGray", IconSetName::Four_ArrowsGray},
      {"Four_RedToBlack", IconSetName::Four_RedToBlack},
      {"Four_Rating", IconSetName::Four_Rating},
      {"Four_TrafficLights", IconSetName::Four_TrafficLights},
      {"Five_Arrows", IconSetName::Five_Arrows},
      {"Five_ArrowsGray", IconSetName::Five_ArrowsGray},
      {"Five_Rating", IconSetName::Five_Rating},
      {"Five_Quarters", IconSetName::Five_Quarters},
  };
  const auto it = kMap.find(s);
  if (it == kMap.end())
    return std::nullopt;
  return it->second;
}

Color ColorFromJson(const JsonValue& j) {
  Color c{};
  if (const JsonValue* r = j.find("r"); r != nullptr)
    c.r = static_cast<std::uint8_t>(r->as_number());
  if (const JsonValue* g = j.find("g"); g != nullptr)
    c.g = static_cast<std::uint8_t>(g->as_number());
  if (const JsonValue* b = j.find("b"); b != nullptr)
    c.b = static_cast<std::uint8_t>(b->as_number());
  if (const JsonValue* a = j.find("a"); a != nullptr)
    c.a = static_cast<std::uint8_t>(a->as_number());
  return c;
}

// Tolerances mirror tests/oracle/cases_cf/README.md so the comparison
// rules don't drift from author intent. Bumping these requires a
// matching README update.
constexpr int kColorChannelTolerance = 2;

// Reusable harness that bundles the sheet, arena, and evaluation
// context the CFHost needs. Mirrors the unit-test harness in
// tests/unit/cf/cf_evaluator_test.cpp; lifted here so the oracle
// binary stays free of test-helper headers from the unit suite.
struct CFOracleHarness {
  Sheet sheet{"Sheet1"};
  Arena arena;
  eval::EvalContext eval_ctx{sheet};

  CFHost MakeHost() {
    CFHost host;
    host.arena = &arena;
    host.registry = &eval::default_registry();
    host.eval_ctx = &eval_ctx;
    return host;
  }
};

CFCellRange MakeRange(std::uint32_t r1, std::uint32_t c1, std::uint32_t r2, std::uint32_t c2) {
  CFCellRange range{};
  range.first.row = r1;
  range.first.col = c1;
  range.last.row = r2;
  range.last.col = c2;
  return range;
}

// True when each channel of `actual` is within `kColorChannelTolerance`
// of `expected`. Used for ColorScale and DataBar fill comparisons.
testing::AssertionResult ColorMatches(const Color& expected, const Color& actual) {
  const int dr = static_cast<int>(actual.r) - static_cast<int>(expected.r);
  const int dg = static_cast<int>(actual.g) - static_cast<int>(expected.g);
  const int db = static_cast<int>(actual.b) - static_cast<int>(expected.b);
  const int da = static_cast<int>(actual.a) - static_cast<int>(expected.a);
  const int max_delta = kColorChannelTolerance;
  const int absdr = dr < 0 ? -dr : dr;
  const int absdg = dg < 0 ? -dg : dg;
  const int absdb = db < 0 ? -db : db;
  const int absda = da < 0 ? -da : da;
  if (absdr <= max_delta && absdg <= max_delta && absdb <= max_delta && absda <= max_delta) {
    return testing::AssertionSuccess();
  }
  return testing::AssertionFailure() << "expected RGBA{" << static_cast<int>(expected.r) << ","
                                     << static_cast<int>(expected.g) << "," << static_cast<int>(expected.b) << ","
                                     << static_cast<int>(expected.a) << "} got RGBA{" << static_cast<int>(actual.r)
                                     << "," << static_cast<int>(actual.g) << "," << static_cast<int>(actual.b) << ","
                                     << static_cast<int>(actual.a) << "} (per-channel tolerance " << max_delta << ")";
}

// DataBar `length_pct` / `axis_position_pct` comparison tolerance, in
// percentage points. Mirrors tests/oracle/cases_cf/README.md.
constexpr double kBarLengthTolerance = 0.5;

// Compares the evaluator's sparse per-cell match list against the golden
// `cells` array for `case_id`. Kind-specific payloads are checked field
// by field; colour channels use `ColorMatches`, bar lengths use
// `kBarLengthTolerance`. This is the single expectation authority: every
// fixture builds its inputs, evaluates, then defers to this comparator.
void VerifyAgainstGolden(std::string_view case_id, const std::vector<CFRangeCellMatches>& actual) {
  const std::vector<JsonValue>* expected_cells = GoldenCellsFor(case_id);
  ASSERT_NE(expected_cells, nullptr) << "no golden cells for case '" << case_id << "'";
  ASSERT_EQ(actual.size(), expected_cells->size()) << "matched-cell count mismatch for case '" << case_id << "'";

  for (std::size_t ci = 0; ci < expected_cells->size(); ++ci) {
    SCOPED_TRACE(testing::Message() << "case '" << case_id << "' cell index " << ci);
    const JsonValue& ecell = (*expected_cells)[ci];
    const CFRangeCellMatches& acell = actual[ci];

    const JsonValue* erow = ecell.find("row");
    const JsonValue* ecol = ecell.find("col");
    ASSERT_NE(erow, nullptr);
    ASSERT_NE(ecol, nullptr);
    EXPECT_EQ(acell.cell.row, static_cast<std::uint32_t>(erow->as_number()));
    EXPECT_EQ(acell.cell.col, static_cast<std::uint32_t>(ecol->as_number()));

    const JsonValue* ematches = ecell.find("matches");
    ASSERT_NE(ematches, nullptr);
    ASSERT_TRUE(ematches->is_array());
    ASSERT_EQ(acell.matches.size(), ematches->as_array().size());

    for (std::size_t mi = 0; mi < acell.matches.size(); ++mi) {
      SCOPED_TRACE(testing::Message() << "match index " << mi);
      const JsonValue& em = ematches->as_array()[mi];
      const CFMatch& am = acell.matches[mi];

      const JsonValue* ekind = em.find("kind");
      ASSERT_NE(ekind, nullptr);
      ASSERT_TRUE(ekind->is_string());
      const std::optional<CFMatchKind> kind = CFMatchKindFromString(ekind->as_string());
      ASSERT_TRUE(kind.has_value()) << "unknown match kind '" << ekind->as_string() << "'";
      EXPECT_EQ(am.kind, *kind);

      if (const JsonValue* eprio = em.find("priority"); eprio != nullptr) {
        EXPECT_EQ(am.priority, static_cast<std::int32_t>(eprio->as_number()));
      }

      switch (*kind) {
        case CFMatchKind::DifferentialFormat: {
          const JsonValue* edxf = em.find("dxf_id");
          ASSERT_NE(edxf, nullptr);
          ASSERT_TRUE(am.dxf_id.has_value());
          EXPECT_EQ(*am.dxf_id, static_cast<std::uint32_t>(edxf->as_number()));
          break;
        }
        case CFMatchKind::ColorScale: {
          const JsonValue* ecolor = em.find("color");
          ASSERT_NE(ecolor, nullptr);
          ASSERT_TRUE(am.resolved_fill_color.has_value());
          EXPECT_TRUE(ColorMatches(ColorFromJson(*ecolor), *am.resolved_fill_color));
          break;
        }
        case CFMatchKind::DataBar: {
          ASSERT_TRUE(am.data_bar_render.has_value());
          const DataBarRender& render = *am.data_bar_render;
          if (const JsonValue* elen = em.find("bar_length_pct"); elen != nullptr) {
            EXPECT_NEAR(render.length_pct, elen->as_number(), kBarLengthTolerance);
          }
          if (const JsonValue* eaxis = em.find("bar_axis_position_pct"); eaxis != nullptr) {
            EXPECT_NEAR(render.axis_position_pct, eaxis->as_number(), kBarLengthTolerance);
          }
          if (const JsonValue* eneg = em.find("is_negative"); eneg != nullptr) {
            EXPECT_EQ(render.is_negative, eneg->as_bool());
          }
          if (const JsonValue* efill = em.find("fill"); efill != nullptr) {
            EXPECT_TRUE(ColorMatches(ColorFromJson(*efill), render.fill));
          }
          break;
        }
        case CFMatchKind::IconSet: {
          ASSERT_TRUE(am.icon_render.has_value());
          const IconRender& render = *am.icon_render;
          if (const JsonValue* ename = em.find("icon_set_name"); ename != nullptr) {
            ASSERT_TRUE(ename->is_string());
            const std::optional<IconSetName> set = IconSetNameFromString(ename->as_string());
            ASSERT_TRUE(set.has_value()) << "unknown icon set '" << ename->as_string() << "'";
            EXPECT_EQ(render.set_name, *set);
          }
          if (const JsonValue* eidx = em.find("icon_index"); eidx != nullptr) {
            EXPECT_EQ(render.icon_index, static_cast<std::uint8_t>(eidx->as_number()));
          }
          break;
        }
      }
    }
  }
}

// ---------------------------------------------------------------------------
// Case 1: cellIs > 50 over A1:A3 = [10, 60, 90].
// Mirrors cases_cf/cf_smoke.yaml :: cellis_greater_than_50.
// Expected: A2 and A3 each yield one DifferentialFormat match with
// dxf_id=7, priority=1; A1 yields no matches and is absent from the
// (sparse) result.
// ---------------------------------------------------------------------------

TEST(CfOracleSmoke, CellIsGreaterThan50) {
  CFOracleHarness harness;
  harness.sheet.set_cell_value(0, 0, Value::number(10.0));
  harness.sheet.set_cell_value(1, 0, Value::number(60.0));
  harness.sheet.set_cell_value(2, 0, Value::number(90.0));

  ConditionalFormat block{};
  block.sqref.push_back(MakeRange(0, 0, 2, 0));
  CFRule rule;
  rule.type = RuleType::CellIs;
  rule.priority = 1;
  rule.dxf_id = 7u;
  rule.op = CellIsOperator::GreaterThan;
  rule.formula1 = "50";
  block.rules.push_back(std::move(rule));
  harness.sheet.mutable_conditional_formats().push_back(std::move(block));

  const CFHost host = harness.MakeHost();
  const std::vector<CFRangeCellMatches> matches = evaluate_cf_for_range(harness.sheet, MakeRange(0, 0, 2, 0), host);

  VerifyAgainstGolden("cellis_greater_than_50", matches);
}

