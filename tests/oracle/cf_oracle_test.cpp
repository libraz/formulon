// Conditional-formatting (CF) oracle smoke test. Pins Formulon's CF
// evaluator output for a small set of hand-authored scenarios so
// behaviour changes to `src/cf/cf_evaluator.cpp` surface as a CI
// failure instead of as a silent rendering regression.
//
// The scenario *inputs* (sheet values and CF rule specs) are built
// programmatically per fixture below, but the *expected outputs* are
// read from the checked-in golden at
//   tests/oracle/golden_cf/<suite>.golden.json
// (path handed in via the FORMULON_CF_GOLDEN_DIR compile define), so
// the golden is the single source of truth for match expectations.
// The Excel-actual golden is regenerated by
// `tools/oracle/cf_oracle_gen.py` (macOS only); the paired input
// artefacts (`cases_cf/<suite>.yaml`, `cases_cf/<suite>.case.json`)
// are kept in shape by the Python validator
// (`tools/oracle/cf_case_schema.py`).
//
// See `tests/oracle/cases_cf/README.md` for the schema and the
// macOS capture roadmap.

