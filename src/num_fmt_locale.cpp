std::string_view localized_builtin_num_fmt(std::uint16_t id, ExcelProfile profile) noexcept {
  const LocaleTable& table = kTables[static_cast<std::size_t>(profile.locale)];
  if (table.latin_thai_ids && id >= 59U && id <= 81U) {
    id = kLatinThaiIds[id - 59U];
  }
  if (table.latin_cjk_ids && ((id >= 27U && id <= 36U) || (id >= 50U && id <= 58U))) {
    id = id >= 32U && id <= 35U ? 21U : 14U;
  }
  for (std::size_t i = 0; i < table.count; ++i) {
    if (table.entries[i].id == id) {
      return kCodes[table.entries[i].code];
    }
  }
  return builtin_num_fmt(id);
}

bool is_builtin_num_fmt_id(std::uint16_t id) noexcept {
  for (std::size_t locale = 0; locale < std::size(kTables); ++locale) {
    const ExcelProfile profile{ExcelHost::kMac365, static_cast<ExcelLocale>(locale)};
    if (!localized_builtin_num_fmt(id, profile).empty()) {
      return true;
    }
  }
  return false;
}

std::optional<std::uint16_t> builtin_num_fmt_id_for_en_us_code(std::string_view code) noexcept {
  const ExcelProfile en_us = mac_365_en_us_profile();
  for (std::uint16_t id = 1; id < 164U && !code.empty(); ++id) {
    if (localized_builtin_num_fmt(id, en_us) == code) {
      return id;
    }
  }
  return std::nullopt;
}

