struct LocaleTable {
  const Override* entries;
  std::size_t count;
  /// Ids 27-36 and 50-58 render as id 14 or 21.
  bool latin_cjk_ids;
  /// Ids 59-81 render as their Latin counterparts (`kLatinThaiIds`).
  bool latin_thai_ids;
};

