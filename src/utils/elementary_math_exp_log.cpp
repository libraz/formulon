constexpr std::uint64_t kHighBitsMask = 0xfffffffff8000000;     // keeps the leading 26 significand bits

// Index and significand of a positive normal x for the 129-entry log tables.
struct LogArgument {
  std::int64_t exponent;
  unsigned index;
  double significand;
};

LogArgument log_argument(std::uint64_t xb) noexcept {
  LogArgument a{};
  a.exponent = static_cast<std::int64_t>(kLogExponentBias + xb) >> 52;
  const std::uint64_t mantissa = xb & 0x000fffffffffffff;
  a.index = static_cast<unsigned>((mantissa + 0x0000100000000000) >> 45);
  a.significand = from_bits(mantissa | kOneBits);
  return a;
}

// r^2 * (r * p1 + p0) * (r * (r + p3) + p2) * (r * (r + p5) + p4).
double log_poly(double r, const std::uint64_t* p) noexcept {
  const double a = std::fma(r, from_bits(p[1]), from_bits(p[0]));
  const double b = std::fma(r, r + from_bits(p[3]), from_bits(p[2]));
  const double c = std::fma(r, r + from_bits(p[5]), from_bits(p[4]));
  double q = r * r;
  q = q * a;
  q = q * b;
  return q * c;
}

// Special arguments of log and log10: NaN, zero, negatives and +inf; false for a positive normal or subnormal.
bool log_special(double x, std::uint64_t* xb, double* out) noexcept {
  if (*xb - kMinNormalBits < 0x7fe0000000000000) {
    return false;
  }
  if (std::isnan(x)) {
    *out = x;
  } else if (x == 0.0) {
    *out = -std::numeric_limits<double>::infinity();
  } else if (x < 0.0) {
    *out = std::numeric_limits<double>::quiet_NaN();
  } else if (static_cast<std::int64_t>(*xb - kMinNormalBits) >= 0) {
    *out = x;  // +inf
  } else {
    *xb = normalised_bits(*xb);
    return false;
  }
  return true;
}

// |y| as an integer-valued double clamped to 2^53, and whether it is an odd integer.
bool is_odd_integer(std::uint64_t abs_y_bits, bool* integral) noexcept {
  const double clamped = from_bits(abs_y_bits <= 0x4340000000000000 ? abs_y_bits : 0x4340000000000000);
  *integral = std::trunc(clamped) == clamped;
  return *integral && (static_cast<std::int64_t>(clamped) & 1) != 0;
}

// x^y for every argument the main path does not take: x not a positive normal, or y outside [2^-65, 2^64) or
// negative. Returns true with `*out` set when the result is decided here; otherwise leaves the main path a positive
// x (`*xb`, a subnormal pre-scaled) and the result sign in `*sign`.
bool pow_special(double x, double y, std::uint64_t* xb, std::uint64_t* sign, double* out) noexcept {
  const std::uint64_t yb = to_bits(y);
  if (*xb == kOneBits) {
    *out = x;
    return true;
  }
  if (yb == kOneBits) {
    *out = std::isnan(x) ? x + x : x;
    return true;
  }
  const std::uint64_t ax = *xb & ~kSignBits;
  const std::uint64_t ay = yb & ~kSignBits;
  const double abs_x = from_bits(ax);
  const double abs_y = from_bits(ay);
  if (ay == 0) {
    *out = 1.0;
    return true;
  }
  if (ay >= kInfBits) {
    if (ay > kInfBits) {
      *out = y + y;
    } else if (ax > kInfBits) {
      *out = x + x;
    } else if (ax == kOneBits) {
      *out = 1.0;
    } else {
      // |x| > 1 with y = +inf, or |x| < 1 with y = -inf, is +inf; the other two are 0.
      const std::uint64_t q = (ax - kOneBits) ^ yb;
      *out = from_bits(kInfBits & ~static_cast<std::uint64_t>(static_cast<std::int64_t>(q) >> 63));
    }
    return true;
  }
  if (ax == 0 || ax >= kInfBits) {
    if (ax > kInfBits) {
      *out = x + x;
      return true;
    }
    bool integral = false;
    const bool odd = ay >= kOneBits && is_odd_integer(ay, &integral);
    const double base = odd ? x : abs_x;
    *out = (yb & kSignBits) != 0 ? 1.0 / base : base;
    return true;
  }
  if ((*xb & kSignBits) != 0) {
    bool integral = false;
    const bool odd = ay >= kOneBits && is_odd_integer(ay, &integral);
    if (ay < kOneBits || !integral) {
      *out = std::numeric_limits<double>::quiet_NaN();
      return true;
    }
    if (odd) {
      *sign = kSignBits;
    }
    *xb = ax;
  }
  const double signed_one = from_bits(*sign | kOneBits);
  if (abs_y > from_bits(0x43f0000000000000)) {  // |y| > 2^64
    if (abs_x == 1.0) {
      *out = signed_one;
    } else {
      *out = (abs_x > 1.0) == (y > 0.0) ? pow_overflow(*sign) : pow_underflow(*sign);
    }
    return true;
  }
  if (abs_y < from_bits(0x3be0000000000000)) {  // |y| < 2^-65: 1 nudged by 2^-65 toward the true side
    const double nudge = from_bits(*sign | 0x3be0000000000000);
    if (abs_x == 1.0) {
      *out = signed_one;
    } else {
      *out = (abs_x > 1.0) == (y > 0.0) ? signed_one + nudge : signed_one - nudge;
    }
    return true;
  }
  if (*xb < 0x0010000000000000) {
    *xb = normalised_bits(*xb);
  }
  return false;
}

