double pow(double x, double y) noexcept {
  std::uint64_t xb = to_bits(x);
  std::uint64_t sign = 0;
  const bool outside =
      xb - 0x0010000000000000 >= 0x7fe0000000000000 || to_bits(y) - 0x3be0000000000000 > 0x0810000000000000;
  double special = 0.0;
  if (outside && pow_special(x, y, &xb, &sign, &special)) {
    return special;
  }
  const std::uint64_t mantissa = xb & 0x000fffffffffffff;
  if (mantissa == 0) {
    // x is a power of two: log2(x) * 128 is exact.
    const auto e = static_cast<std::int64_t>(xb - kOneBits);
    if (e == 0) {
      return from_bits(sign | kOneBits);
    }
    const double l = static_cast<double>(e) * 0x1p-45;
    const double t = l * y;
    return pow_exp2(t, std::fma(l, y, -t), sign);
  }
  const auto offset = static_cast<unsigned>(((mantissa + 0x0000100000000000) & 0x001fe00000000000) >> 41);
  const std::uint64_t* entry = kPowLogTable + offset / 8;
  const auto k = static_cast<std::int64_t>(xb + kLogExponentBias) >> 52;
  const double inv = from_bits((entry[0] & 0xffffffff) << 32);
  // r = m * inv - 1 as a double-double r + r_lo.
  const double m = from_bits(mantissa | kOneBits);
  const double product = inv * m;
  const double m_hi = from_bits((mantissa | kOneBits) & 0xffffffffffe00000);
  const double m_lo = m - m_hi;
  const double err = std::fma(inv, m_hi, -product);
  const double r = product - 1.0;
  const double r_lo = std::fma(inv, m_lo, err);
  double tail = std::fma(r, from_bits(kPowLogPoly[0]), from_bits(kPowLogPoly[1]));
  for (int i = 2; i < 5; ++i) {
    tail = std::fma(r, tail, from_bits(kPowLogPoly[i]));
  }
  double r4 = r * r;
  r4 = r4 * r4;
  tail = r4 * tail;
  // Two compensated Horner steps (a r + c, then (.) r + e) and a final compensated product with r.
  const double a = from_bits(kPowLogPoly[5]);
  const double c = from_bits(kPowLogPoly[7]);
  const double e = from_bits(kPowLogPoly[9]);
  const double h1 = std::fma(a, r, c);
  double l1 = std::fma(from_bits(kPowLogPoly[6]), r, from_bits(kPowLogPoly[8]));
  double t1 = h1 - c;
  t1 = std::fma(a, r, -t1);
  l1 = std::fma(a, r_lo, l1);
  l1 = t1 + l1;
  const double h2 = std::fma(h1, r, e);
  double l2 = std::fma(l1, r, from_bits(kPowLogPoly[10]));
  double t2 = h2 - e;
  t2 = std::fma(h1, r, -t2);
  l2 = std::fma(h1, r_lo, l2);
  l2 = t2 + l2;
  const double h3 = h2 * r;
  l2 = l2 * r;
  double l3 = std::fma(h2, r, -h3);
  l2 = std::fma(h2, r_lo, l2);
  l3 = l3 + l2;
  const auto kd = static_cast<double>(k);
  const double log_c = from_bits(entry[1]);
  double hi = kd + log_c;
  hi = hi + h3;
  hi = hi + tail;
  hi = from_bits(to_bits(hi) & 0xfffffffffffffffe);
  double lo = kd - hi;
  lo = lo + log_c;
  lo = lo + h3;
  lo = lo + tail;
  double lo_total = from_bits(entry[0] & 0xffffffff00000000);
  lo_total = lo_total + lo;
  lo_total = lo_total + l3;
  const double y128 = y * 128.0;
  const double t = y128 * hi;
  double t_lo = std::fma(y128, hi, -t);
  t_lo = std::fma(y128, lo_total, t_lo);
  return pow_exp2(t, t_lo, sign);
}

double exp(double x) noexcept {
  const std::uint64_t xb = to_bits(x);
  if (xb >= kExpOverflowBits && static_cast<std::int64_t>(xb) >= static_cast<std::int64_t>(kExpUnderflowBits)) {
    if (!(x < 0.0)) {
      return x * from_bits(kLargestFiniteBits);
    }
    const double tiny = from_bits(xb + kMinNormalBits < xb ? 0 : kMinNormalBits);
    return tiny * tiny;
  }
  const double scaled = x * from_bits(kExpScaleHi);
  const auto k = static_cast<std::int64_t>(std::floor(scaled));
  double f = scaled - static_cast<double>(k);
  const double err = std::fma(-x, from_bits(kExpScaleHi), scaled);
  const double lo = std::fma(x, from_bits(kExpScaleLo), -err);
  const std::uint64_t* entry = kExpTable + 2 * (k & 127);
  const double base = from_bits(entry[0]);
  const double correction = from_bits(entry[1]) + lo;
  const double a = f + from_bits(kExpPoly[0]);
  const double b = f + from_bits(kExpPoly[1]);
  f = f + correction;
  const double p = std::fma(f, a, from_bits(kExpPoly[2]));
  const double q = std::fma(f, b, from_bits(kExpPoly[3]));
  double r = f * from_bits(kExpPoly[4]);
  r = r * p;
  r = r * q;
  const std::int64_t n = k >> 7;
  if (n + 0x3fe < 0) {
    // Subnormal result: scale into range, add 1 to round once, then remove it.
    double s = from_bits(to_bits(base) + (static_cast<std::uint64_t>(n + 0x3fe) << 52));
    const double u = s + 1.0;
    double w = s - (u - 1.0);
    w = std::fma(s, r, w);
    s = u + w;
    return (s - 1.0) * from_bits(kMinNormalBits);
  }
  return from_bits(to_bits(std::fma(r, base, base)) + (static_cast<std::uint64_t>(n) << 52));
}

double log(double x) noexcept {
  std::uint64_t xb = to_bits(x);
  double special = 0.0;
  if (log_special(x, &xb, &special)) {
    return special;
  }
  const LogArgument a = log_argument(xb);
  const double inv = from_bits(kLogTable[a.index][0]);
  const double log_hi = from_bits(kLogTable[a.index][1]);
  const double log_lo = from_bits(kLogTable[a.index][2]);
  const double r = std::fma(a.significand, inv, -1.0);
  const double q = log_poly(r, kLogPoly);
  if (a.exponent != 0) {
    const auto k = static_cast<double>(a.exponent);
    double lo = std::fma(k, from_bits(kLn2Lo), log_lo);
    const double hi = std::fma(k, from_bits(kLn2Hi), log_hi);
    lo = lo + q;
    return hi + (r + lo);
  }
  // Exponent 0: r is split so its leading part adds to log(c) exactly.
  const double product = inv * a.significand;
  const double s = product - 1.0;
  const double err = std::fma(inv, a.significand, -product);
  const double r_hi = from_bits(to_bits(s) & kHighBitsMask);
  double t = s - r_hi;
  t = err + t;
  const double head = r_hi + log_hi;
  t = t + log_lo;
  t = t + q;
  return head + t;
}

double log10(double x) noexcept {
  std::uint64_t xb = to_bits(x);
  double special = 0.0;
  if (log_special(x, &xb, &special)) {
    return special;
  }
  const LogArgument a = log_argument(xb);
  const double inv = from_bits(kLog10Table[a.index][0]);
  const double log_c = from_bits(kLog10Table[a.index][1]);
  const double r = std::fma(a.significand, inv, -1.0);
  const double q = log_poly(r, kLog10Poly);
  if (a.exponent != 0) {
    const auto k = static_cast<double>(a.exponent);
    double hi = from_bits(to_bits(log_c) & kHighBitsMask);
    double lo = log_c - hi;
    lo = lo + q;
    hi = std::fma(k, from_bits(kLog10Of2Hi), hi);
    double sum = k * from_bits(kLog10Of2Lo);
    sum = sum + r * from_bits(kInvLn10);
    sum = sum + lo;
    return sum + hi;
  }
  const double product = inv * a.significand;
  const double s = product - 1.0;
  const double err = std::fma(inv, a.significand, -product);
  double sum = r * from_bits(kInvLn10Lo);
  double r_hi = from_bits(to_bits(r) & kHighBitsMask);
  double t = s - r_hi;
  r_hi = r_hi * from_bits(kInvLn10Hi);
  t = err + t;
  const double head = log_c + r_hi;
  double tail = head - log_c;
  sum = std::fma(t, from_bits(kInvLn10Hi), sum);
  tail = r_hi - tail;
  sum = sum + tail;
  sum = sum + q;
  return sum + head;
}

