// Significand m of a positive x as [1, 2) and its exponent, a subnormal x first scaled into the normal range.
std::uint64_t normalised_bits(std::uint64_t xb) noexcept {
  const double d = from_bits(xb | kOneBits) - 1.0;
  return to_bits(d) + 0xc020000000000000;
}

double pow_overflow(std::uint64_t sign) noexcept {
  const double c = from_bits(0x7fe0000000000001);
  return c * from_bits(sign | to_bits(c));
}

double pow_underflow(std::uint64_t sign) noexcept {
  const double c = from_bits(0x0010000000000001);
  return c * from_bits(sign | to_bits(c));
}

// 2^(t/128) for t = t_hi + t_lo, signed by `sign`.
double pow_exp2(double t, double t_lo, std::uint64_t sign) noexcept {
  if (t > from_bits(0x4100040000000000)) {
    return pow_overflow(sign);
  }
  if (t < from_bits(0xc100cc0000000000)) {
    return pow_underflow(sign);
  }
  const double whole = std::floor(t);
  const auto n = static_cast<std::int64_t>(whole);
  const double f = t - whole;
  const std::uint64_t* e = kPowExpTable + 2 * (n & 127);
  double u = t_lo - from_bits(e[1]);
  u = u + f;
  double p = std::fma(f, from_bits(kPowExpPoly[0]), from_bits(kPowExpPoly[1]));
  p = std::fma(f, p, from_bits(kPowExpPoly[2]));
  p = std::fma(u, p, from_bits(kPowExpPoly[3]));
  p = std::fma(u, p, from_bits(kPowExpPoly[4]));
  p = u * p;
  std::uint64_t half = (static_cast<std::uint64_t>(n) << 44) & 0xfff0000000000000;
  std::uint64_t rest = (static_cast<std::uint64_t>(n) << 45) & 0xfff0000000000000;
  rest -= half;
  half ^= sign;
  double r = from_bits(half + e[0]);
  r = std::fma(r, p, r);
  return r * from_bits(rest + kOneBits);
}

