std::uint32_t sbcs_decode_byte(SbcsCodepage codepage, std::uint8_t byte) noexcept {
  if (byte < 0x80u) {
    return byte;
  }
  if (codepage == SbcsCodepage::kCp932) {
    return byte;
  }
  if (codepage == SbcsCodepage::kDbcsHighBlank) {
    // 0x80 and 0xFF keep their own code point; every other high byte is a space.
    return byte == 0x80u || byte == 0xFFu ? byte : 0x20u;
  }
  return high_table(codepage)[static_cast<std::size_t>(byte - 0x80u)];
}

int sbcs_encode_codepoint(SbcsCodepage codepage, std::uint32_t codepoint) noexcept {
  if (codepoint < 0x80u) {
    return static_cast<int>(codepoint);
  }
  if (codepage == SbcsCodepage::kCp932) {
    if (codepoint >= 0xFF61u && codepoint <= 0xFF9Fu) {
      return static_cast<int>(0xA1u + codepoint - 0xFF61u);
    }
    return -1;
  }
  if (codepage == SbcsCodepage::kDbcsHighBlank) {
    return -1;
  }
  // Scan from the top: Mac Thai repeats tone marks at 0x83-0x9C as positional
  // variants, and the plain form is the last slot holding the code point.
  const auto& table = high_table(codepage);
  for (std::size_t i = table.size(); i > 0; --i) {
    if (table[i - 1] == codepoint && codepoint != 0xFFFDu) {
      return static_cast<int>(i - 1 + 0x80u);
    }
  }
  return -1;
}

