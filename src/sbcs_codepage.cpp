const std::array<std::uint32_t, 128>& high_table(SbcsCodepage codepage) noexcept {
  switch (codepage) {
    case SbcsCodepage::kWindows1252:
      return kWindows1252High;
    case SbcsCodepage::kMacThai:
      return kMacThaiHigh;
    default:
      return kMacRomanHigh;
  }
}

